// Mechanical test-quality flags (SPEC 11.2). A flag is not a verdict: Lazarus reviews each one.
// Works on JavaScript/TypeScript (test/it blocks) and Python (def test_ functions); other languages are scanned for
// skip markers and always-true assertions only.
import crypto from 'node:crypto';

export const RULES = {
  'always-true': 'asserts something that is always true',
  'no-assertions': 'has no assertions',
  'runs-only': 'only checks that the code runs without error',
  snapshot: 'snapshot of output generated by the code under test, with no check that it is correct',
  'mocks-unit': 'mocks the local module it is meant to test',
  skipped: 'is skipped, disabled or expected to fail',
  'deleted-test': 'a test that existed in an earlier cycle is gone',
  'assertion-changed': 'the assertions of a test changed since an earlier cycle',
};

const ASSERT = /\b(assert\w*|expect|should|verify|self\.assert\w*)\b|\bt\.(ok|equal|is|deepEqual|true|false|throws|like|match)\b/;
const ALWAYS_TRUE = [
  /expect\(\s*(true|1|"[^"]*"|'[^']*'|`[^`]*`)\s*\)\s*\.\s*(toBe|toEqual|toStrictEqual)\(\s*\1\s*\)/,
  /expect\(\s*true\s*\)\s*\.\s*(toBeTruthy|toBeTrue)\(\)/,
  /\bassert(\.ok|\.isTrue)?\(\s*(true|1)\s*\)/,
  /\bassert\.(equal|strictEqual|deepEqual|deepStrictEqual|is)\(\s*(true|false|\d+|"[^"]*"|'[^']*')\s*,\s*\2\s*\)/,
  /\bassert\s+True\b(?!\s*==)/,
  /\bself\.assertTrue\(\s*True\s*\)/,
  /\bassert\s+1\s*==\s*1\b/,
];
const SKIP = /\.skip\(|\bxit\(|\bxtest\(|\bxdescribe\(|\b(test|it)\.(todo|fixme|fails)\(|@pytest\.mark\.(skip|skipif|xfail)|@unittest\.(skip|expectedFailure)|\{\s*(skip|todo)\s*:\s*(true|['"`])|\bt\.skip\(|\bt\.todo\(/;
const RUNS_ONLY = /doesNotThrow|not\s*\.\s*toThrow|\bassertDoesNotThrow\b/;
const SNAPSHOT = /toMatchSnapshot|toMatchInlineSnapshot|assert_match_snapshot|\bmatchSnapshot\b/;
const MOCKS_LOCAL = /\b(?:jest|vi)\.mock\(\s*['"`](\.{1,2}\/[^'"`]+)['"`]|\bmock\.module\(\s*['"`](\.{1,2}\/[^'"`]+)['"`]/;

const hash = (s) => crypto.createHash('sha1').update(s).digest('hex').slice(0, 6);
const lineOf = (text, idx) => text.slice(0, idx).split('\n').length;

// Test bodies as { name, start, body } with start = character offset of the test declaration.
export function testBlocks(text, file) {
  const out = [];
  if (/\.py$/.test(file)) {
    const lines = text.split('\n');
    let off = 0;
    for (let i = 0; i < lines.length; i++) {
      const m = lines[i].match(/^(\s*)(?:async\s+)?def\s+(test\w*)\s*\(/);
      if (m) {
        const indent = m[1].length;
        let j = i + 1;
        while (j < lines.length && (!lines[j].trim() || lines[j].match(/^(\s*)/)[1].length > indent)) j++;
        out.push({ name: m[2], start: off, body: lines.slice(i, j).join('\n') });
      }
      off += lines[i].length + 1;
    }
    return out;
  }
  const re = /\b(?:test|it)(?:\.\w+)?\s*\(\s*(['"`])((?:\\.|(?!\1).)*)\1/g;
  let m;
  while ((m = re.exec(text))) {
    let i = text.indexOf('{', m.index + m[0].length), depth = 0, end = -1;
    const arrow = text.slice(m.index + m[0].length, i === -1 ? undefined : i);
    if (i === -1 || !/(=>|function)/.test(arrow)) { // expression-bodied arrow: take to the matching paren
      let p = text.indexOf('(', m.index), d = 0;
      for (let k = p; k < text.length; k++) { if (text[k] === '(') d++; else if (text[k] === ')' && --d === 0) { end = k; break; } }
      out.push({ name: m[2], start: m.index, body: text.slice(m.index, end === -1 ? undefined : end + 1) });
      continue;
    }
    for (let k = i; k < text.length; k++) { if (text[k] === '{') depth++; else if (text[k] === '}' && --depth === 0) { end = k; break; } }
    out.push({ name: m[2], start: m.index, body: text.slice(m.index, end === -1 ? undefined : end + 1) });
  }
  return out;
}

const assertionLines = (body) => body.split('\n').filter((l) => ASSERT.test(l)).map((l) => l.trim()).join('\n');

// Scan one file. Returns flags: { id, rule, file, line, test, detail }.
export function scanFile(file, text) {
  const flags = [];
  const add = (rule, test, idx, extra = '') => flags.push({ id: `TQ-${hash(`${rule}|${file}|${test}`)}`, rule, file, line: lineOf(text, idx), test, detail: `${RULES[rule]}${extra}` });
  const blocks = testBlocks(text, file);
  for (const b of blocks) {
    if (SKIP.test(b.body.split('\n')[0]) || SKIP.test(text.slice(Math.max(0, b.start - 60), b.start + 1))) add('skipped', b.name, b.start);
    const hasAssert = ASSERT.test(b.body);
    if (!hasAssert) add('no-assertions', b.name, b.start);
    else if (ALWAYS_TRUE.some((r) => r.test(b.body))) add('always-true', b.name, b.start);
    else if (RUNS_ONLY.test(b.body) && assertionLines(b.body).split('\n').every((l) => RUNS_ONLY.test(l))) add('runs-only', b.name, b.start);
    if (SNAPSHOT.test(b.body)) add('snapshot', b.name, b.start);
  }
  const mock = text.match(MOCKS_LOCAL);
  if (mock) add('mocks-unit', mock[1] || mock[2], mock.index, `: ${mock[1] || mock[2]}`);
  // skip markers outside any recognised block (for example describe.skip) and always-true in unrecognised languages
  if (!blocks.length) {
    for (const r of ALWAYS_TRUE) { const m = text.match(r); if (m) add('always-true', '(file)', m.index); }
    const s = text.match(SKIP); if (s) add('skipped', '(file)', s.index);
  } else {
    const d = text.match(/\b(describe|suite|context)\.(skip|todo)\(|\bxdescribe\(/);
    if (d) add('skipped', '(suite)', d.index);
  }
  return flags;
}

// Inventory of a file's tests: name -> hash of its assertion lines. Used to catch deleted or quietly rewritten tests.
export function inventoryOf(file, text) {
  return Object.fromEntries(testBlocks(text, file).map((b) => [`${file}::${b.name}`, hash(assertionLines(b.body))]));
}

export function compareInventory(prev, now) {
  const flags = [];
  for (const k of Object.keys(prev)) {
    const [file, test] = k.split('::');
    if (!(k in now)) flags.push({ id: `TQ-${hash(`deleted-test|${file}|${test}`)}`, rule: 'deleted-test', file, line: 0, test, detail: RULES['deleted-test'] });
    else if (now[k] !== prev[k]) flags.push({ id: `TQ-${hash(`assertion-changed|${file}|${test}`)}`, rule: 'assertion-changed', file, line: 0, test, detail: RULES['assertion-changed'] });
  }
  return flags;
}
